package com.wgzhao.addax.admin.config.schema;

import com.wgzhao.addax.admin.config.EtlTableView;
import lombok.extern.slf4j.Slf4j;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

/** Creates the reconciliation result table. */
@Slf4j
public final class ReconcileSchema
{
        public static final String CREATE_RECONCILE_TABLE_SQL = """
        create table if not exists public.etl_reconcile (
            id bigint generated by default as identity primary key,
            tid bigint not null,
            execution_id bigint,
            biz_date date not null,
            source_rows bigint,
            target_rows bigint,
            diff bigint,
            tolerance bigint not null default 0,
            status varchar(16) not null,
            message varchar(1000),
            created_at timestamp without time zone not null default current_timestamp
        )
        """;

        public static final String CREATE_RECONCILE_INDEXES_SQL = """
        create index if not exists idx_etl_reconcile_tid_time
            on public.etl_reconcile (tid, created_at desc, id desc);
        create index if not exists idx_etl_reconcile_execution
            on public.etl_reconcile (execution_id);
        create index if not exists idx_etl_reconcile_biz_date
            on public.etl_reconcile (biz_date)
        """;

    public static void ensureTable(Statement statement) throws SQLException
    {
        statement.execute(CREATE_RECONCILE_TABLE_SQL);
        statement.execute(CREATE_RECONCILE_INDEXES_SQL);
    }

    private ReconcileSchema()
    {
    }
}
