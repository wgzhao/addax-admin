package com.wgzhao.addax.admin.config.schema;

import com.wgzhao.addax.admin.config.EtlTableView;
import lombok.extern.slf4j.Slf4j;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

/** Upgrades the collection definition table, its column mappings and route keys. */
@Slf4j
public final class TableSchema
{
        public static final String ADD_TARGET_OPTIONS_SQL =
        "alter table public.etl_table add column if not exists target_options jsonb";

        public static final String ADD_SCHEMA_OWNERSHIP_SQL = """
        alter table public.etl_table
            add column if not exists schema_management_mode varchar(16) not null default 'MANAGED',
            add column if not exists target_schema_fingerprint varchar(64)
        """;

        public static final String ADD_TABLE_RETIREMENT_SQL = """
        alter table public.etl_table
            add column if not exists retired_at timestamp without time zone,
            add column if not exists retired_by varchar(100)
        """;

        public static final String WIDEN_TABLE_IDENTIFIERS_SQL = """
        alter table public.etl_table alter column source_db type varchar(64);
        alter table public.etl_table alter column source_table type varchar(255)
        """;

        public static final String ADD_COLUMN_SOURCE_META_SQL =
        "alter table public.etl_column add column if not exists source_meta jsonb";

        public static final String CREATE_COLUMN_MAPPING_SQL = """
        create table if not exists public.etl_column_mapping (
            id bigint generated by default as identity primary key,
            tid bigint not null references public.etl_table(id) on delete restrict,
            source_column_name varchar(255) not null,
            target_column_name varchar(255) not null,
            ordinal_no integer not null,
            created_at timestamp without time zone not null default current_timestamp,
            updated_at timestamp without time zone not null default current_timestamp
        )
        """;

        public static final String BACKFILL_COLUMN_MAPPING_SQL = """
        insert into public.etl_column_mapping (
            tid, source_column_name, target_column_name, ordinal_no
        )
        select distinct on (c.tid, lower(btrim(regexp_replace(c.column_name, '^__deleted__', ''))))
               c.tid,
               btrim(regexp_replace(c.column_name, '^__deleted__', '')),
               btrim(regexp_replace(c.column_name, '^__deleted__', '')),
               coalesce(c.column_id, 0)
          from public.etl_column c
         where btrim(regexp_replace(c.column_name, '^__deleted__', '')) <> ''
           and not exists (
               select 1 from public.etl_column_mapping m where m.tid = c.tid
           )
         order by c.tid,
                  lower(btrim(regexp_replace(c.column_name, '^__deleted__', ''))),
                  (left(c.column_name, 11) = '__deleted__'),
                  c.column_id nulls last,
                  c.column_name
        """;

        public static final String CREATE_COLUMN_MAPPING_INDEXES_SQL = """
        create unique index if not exists uk_column_mapping_tid_target
            on public.etl_column_mapping (tid, lower(target_column_name))
        """;

        public static final String MIGRATE_COLUMN_MAPPING_SOURCE_INDEX_SQL = """
        do $$
        declare idxdef text;
        begin
            select indexdef into idxdef
              from pg_indexes
             where schemaname = 'public' and indexname = 'uk_column_mapping_tid_source';
            if idxdef is null then
                create unique index uk_column_mapping_tid_source
                    on public.etl_column_mapping (tid, source_column_name);
            elsif idxdef like '%lower(%' then
                drop index public.uk_column_mapping_tid_source;
                create unique index uk_column_mapping_tid_source
                    on public.etl_column_mapping (tid, source_column_name);
            end if;
        end
        $$
        """;

        public static final String ADD_TABLE_SCOPE_INDEXES_SQL = """
        create index if not exists idx_etl_table_sid_target on public.etl_table (sid, target_id);
        create index if not exists idx_etl_table_target_db on public.etl_table (target_id, target_db);
        """;

        public static final String ADD_TABLE_ROUTE_KEYS_SQL = """
        alter table public.etl_table
            add column if not exists source_route_key varchar(400),
            add column if not exists target_slot_key varchar(300)
        """;

        public static final String CREATE_TABLE_ROUTE_KEY_INDEXES_SQL = """
        create unique index if not exists uk_etl_table_active_source_route
            on public.etl_table (sid, target_id, source_route_key)
            where retired_at is null and source_route_key is not null;
        create unique index if not exists uk_etl_table_active_target_slot
            on public.etl_table (sid, target_id, target_slot_key)
            where retired_at is null and target_slot_key is not null
        """;

        public static final String BACKFILL_TARGET_ID_SQL = """
        update public.etl_table t
           set target_id = coalesce(
               (select id from public.etl_target where is_default = true order by id limit 1),
               (select id from public.etl_target where enabled = true order by id limit 1)
           )
         where t.target_id is null
           and exists (select 1 from public.etl_target where is_default = true or enabled = true)
        """;

        public static final String DROP_TABLE_KIND_SQL =
        "alter table public.etl_table drop column if exists kind";

        public static final String BACKFILL_SQL = """
        update public.etl_table
           set target_options = jsonb_build_object('hdfs', jsonb_build_object(
                 'partKind', coalesce(part_kind, 'D'),
                 'partName', coalesce(part_name, ''),
                 'partFormat', coalesce(nullif(part_format, ''), 'yyyyMMdd'),
                 'storageFormat', coalesce(nullif(storage_format, ''), 'orc'),
                 'compressFormat', coalesce(nullif(compress_format, ''), 'snappy')))
         where target_options is null
        """;

        public static final String DROP_LEGACY_COLUMNS_SQL = """
        alter table public.etl_table
            drop column if exists part_kind,
            drop column if exists part_name,
            drop column if exists part_format,
            drop column if exists storage_format,
            drop column if exists compress_format
        """;

        public static final String LEGACY_COLUMN = "part_name";

    public static boolean hasLegacyHiveColumns(Connection connection) throws SQLException
    {
        return SchemaSupport.exists(connection, "columns", "etl_table", LEGACY_COLUMN);
    }

    public static void upgradeColumns(Connection connection, Statement statement, boolean hasSource)
        throws SQLException
    {
        statement.execute(ADD_TARGET_OPTIONS_SQL);
        statement.execute(ADD_SCHEMA_OWNERSHIP_SQL);
        statement.execute(ADD_TABLE_RETIREMENT_SQL);
        LogSchema.widenIdentifiers(statement);
        // Same rule as the source-url widening: only pay the view drop when a column is narrower
        // than the current definition.
        if (hasSource && SchemaSupport.exists(connection, "tables", "etl_target", null)
            && (SchemaSupport.needsWidening(connection, "etl_table", "source_db", 64)
                || SchemaSupport.needsWidening(connection, "etl_table", "source_table", 255))) {
            statement.execute(EtlTableView.DROP_SQL);
            statement.execute(WIDEN_TABLE_IDENTIFIERS_SQL);
        }
        if (SchemaSupport.exists(connection, "tables", "etl_column", null)) {
            statement.execute(ADD_COLUMN_SOURCE_META_SQL);
            statement.execute(CREATE_COLUMN_MAPPING_SQL);
            int mappings = statement.executeUpdate(BACKFILL_COLUMN_MAPPING_SQL);
            if (mappings > 0) {
                log.info("Backfilled {} column mapping(s) from etl_column", mappings);
            }
            statement.execute(CREATE_COLUMN_MAPPING_INDEXES_SQL);
            statement.execute(MIGRATE_COLUMN_MAPPING_SOURCE_INDEX_SQL);
        }
    }

    public static void backfillLegacyHiveOptions(Statement statement) throws SQLException
    {
        int updated = statement.executeUpdate(BACKFILL_SQL);
        log.info("Backfilled target_options for {} etl_table row(s)", updated);
    }

    public static void dropLegacyColumns(Statement statement) throws SQLException
    {
        statement.execute(DROP_LEGACY_COLUMNS_SQL);
        log.info("Migrated etl_table Hive attributes (part_*/storage/compress) into target_options");
    }

    public static void upgradeTargetScope(Connection connection, Statement statement) throws SQLException
    {
        if (SchemaSupport.exists(connection, "columns", "etl_table", "target_id")) {
            int backfilled = statement.executeUpdate(BACKFILL_TARGET_ID_SQL);
            if (backfilled > 0) {
                log.info("Backfilled target_id for {} etl_table row(s)", backfilled);
            }
            statement.execute(ADD_TABLE_SCOPE_INDEXES_SQL);
            statement.execute(ADD_TABLE_ROUTE_KEYS_SQL);
            statement.execute(CREATE_TABLE_ROUTE_KEY_INDEXES_SQL);
        }
    }

    public static void dropKindColumn(Connection connection, Statement statement) throws SQLException
    {
        if (!SchemaSupport.exists(connection, "columns", "etl_table", "kind")) {
            return;
        }
        statement.execute(EtlTableView.DROP_SQL);
        statement.execute(DROP_TABLE_KIND_SQL);
        log.info("Dropped the unused etl_table.kind column");
    }

    private TableSchema()
    {
    }
}
