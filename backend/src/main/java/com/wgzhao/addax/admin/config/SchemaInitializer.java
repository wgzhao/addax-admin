    private static final String ADD_EXECUTION_CONTEXT_SQL = """
        alter table public.etl_statistic add column if not exists execution_id bigint;
        alter table public.etl_jour add column if not exists execution_id bigint;
        alter table public.etl_jour add column if not exists context_snapshot jsonb;
        alter table public.addax_log add column if not exists execution_id bigint
        """;

    private static final String CREATE_EXECUTION_CONTEXT_INDEXES_SQL = """
        create index if not exists idx_etl_statistic_execution on public.etl_statistic (execution_id);
        create index if not exists idx_etl_jour_execution on public.etl_jour (execution_id);
        create index if not exists idx_addax_log_execution on public.addax_log (execution_id)
        """;

    private static final String ADD_EXECUTION_FOREIGN_KEYS_SQL = """
        do $$
        begin
            if not exists (select 1 from pg_constraint where conname = 'etl_execution_tid_fk') then
                alter table public.etl_execution
                    add constraint etl_execution_tid_fk
                    foreign key (tid) references public.etl_table(id) on delete restrict;
            end if;
            if not exists (select 1 from pg_constraint where conname = 'etl_statistic_execution_fk') then
                alter table public.etl_statistic
                    add constraint etl_statistic_execution_fk
                    foreign key (execution_id) references public.etl_execution(id) on delete restrict;
            end if;
            if not exists (select 1 from pg_constraint where conname = 'etl_jour_execution_fk') then
                alter table public.etl_jour
                    add constraint etl_jour_execution_fk
                    foreign key (execution_id) references public.etl_execution(id) on delete restrict;
            end if;
            if not exists (select 1 from pg_constraint where conname = 'addax_log_execution_fk') then
                alter table public.addax_log
                    add constraint addax_log_execution_fk
                    foreign key (execution_id) references public.etl_execution(id) on delete restrict;
            end if;
        end
        $$
        """;

    private static final String BACKFILL_SQL = """
        update public.etl_table
           set target_options = jsonb_build_object('hdfs', jsonb_build_object(
                 'partKind', coalesce(part_kind, 'D'),
                 'partName', coalesce(part_name, ''),
                 'partFormat', coalesce(nullif(part_format, ''), 'yyyyMMdd'),
                 'storageFormat', coalesce(nullif(storage_format, ''), 'orc'),
                 'compressFormat', coalesce(nullif(compress_format, ''), 'snappy')))
         where target_options is null
        """;

    private static final String DROP_LEGACY_COLUMNS_SQL = """
        alter table public.etl_table
            drop column if exists part_kind,
            drop column if exists part_name,
            drop column if exists part_format,
            drop column if exists storage_format,
            drop column if exists compress_format
        """;

    /**
     * Marker of the pre-4.2.1 Hive attributes: present means the target-options move has not run yet.
     */
    private static final String LEGACY_COLUMN = "part_name";

    private final JdbcTemplate jdbcTemplate;
    private final ObjectMapper objectMapper;
    private final com.wgzhao.addax.admin.common.JdbcDriverRegistry driverRegistry;

    @PostConstruct
    public void migrate()
    {
        jdbcTemplate.execute((ConnectionCallback<Void>) connection -> {
            boolean autoCommit = connection.getAutoCommit();
            connection.setAutoCommit(false);
            try (Statement statement = connection.createStatement())
            {
                statement.execute("select pg_advisory_xact_lock(" + MIGRATION_LOCK_KEY + ")");
                upgrade(connection, statement);
                connection.commit();
                return null;
            }
            catch (SQLException | RuntimeException e)
            {
                connection.rollback();
                throw e;
            }
            finally
            {
                connection.setAutoCommit(autoCommit);
            }
        });
    }

    private void upgrade(Connection connection, Statement statement) throws SQLException
    {
        statement.execute(CREATE_AUDIT_EVENT_SQL);
        statement.execute(CREATE_AUDIT_INDEXES_SQL);
        statement.execute(CREATE_AUDIT_APPEND_ONLY_SQL);
        statement.execute(CREATE_AUDIT_APPEND_ONLY_TRIGGER_SQL);
        statement.execute(CREATE_APP_MIGRATION_SQL);
        // Alerts do not depend on the collection schema; create them before the
        // etl table check so an installation without sources can still alert.
        statement.execute(CREATE_ALERT_TABLES_SQL);
        statement.execute(CREATE_ALERT_INDEXES_SQL);
        // Authentication state is independent of the collection schema; upgrade it even on an
        // installation that has never created a source.
        if (exists(connection, "tables", "users", null))
        {
            statement.execute(ADD_USER_AUTH_VERSION_SQL);
            statement.execute(ADD_USER_PROFILE_COLUMNS_SQL);
            statement.execute(CREATE_USER_SOURCE_GRANT_SQL);
        }
        if (exists(connection, "tables", "user_notification", null))
        {
            int purged = statement.executeUpdate(PURGE_LEGACY_COLLECT_NOTIFICATIONS_SQL);
            if (purged > 0)
            {
                log.info("Purged {} legacy collection notification row(s) with the pre-4.4.1 title", purged);
            }
        }
        boolean hasSource = exists(connection, "tables", "etl_source", null);
        boolean hasTable = exists(connection, "tables", "etl_table", null);
        if (!hasSource && !hasTable)
        {
            log.info("etl_source/etl_table not found, skip schema migration");
            return;
        }
        if (hasSource)
        {
            statement.execute(ADD_CALENDAR_COLUMN_SQL);
            statement.execute(ADD_SOURCE_CONNECT_CONFIG_SQL);
            if (exists(connection, "columns", "etl_source", "code"))
            {
                statement.execute(EtlTableView.DROP_SQL);
                statement.execute(DROP_SOURCE_CODE_SQL);
                log.info("Dropped the legacy etl_source.code column");
            }
            // PostgreSQL refuses to alter a column type while a view selects it. Drop the view only
            // when the widening actually runs: an unconditional drop forced a view recreation (and a
            // migration log line) on every single startup of a converged database.
            if (needsWidening(connection, "etl_source", "url", 1000))
            {
                statement.execute(EtlTableView.DROP_SQL);
                statement.execute(WIDEN_SOURCE_URL_SQL);
            }
            int backfilledTypes = statement.executeUpdate(BACKFILL_DB_TYPE_SQL);
            if (backfilledTypes > 0)
            {
                log.info("Backfilled db_type for {} etl_source row(s)", backfilledTypes);
            }
            if (statement.executeUpdate(SEED_WORK_DAY_DICT_SQL) > 0)
            {
                log.info("Seeded the work-day calendar dictionary (code {})", WORK_DAY_DICT_CODE);
            }
        }
        boolean legacyHiveColumns = hasTable && exists(connection, "columns", "etl_table", LEGACY_COLUMN);
        if (hasTable)
        {
            statement.execute(ADD_TARGET_OPTIONS_SQL);
            statement.execute(ADD_SCHEMA_OWNERSHIP_SQL);
            statement.execute(ADD_TABLE_RETIREMENT_SQL);
            statement.execute(WIDEN_LOG_IDENTIFIERS_SQL);
            // Same rule as the source-url widening: only pay the view drop when a column is narrower
            // than the current definition.
            if (hasSource && exists(connection, "tables", "etl_target", null)
                && (needsWidening(connection, "etl_table", "source_db", 64)
                    || needsWidening(connection, "etl_table", "source_table", 255)))
            {
                statement.execute(EtlTableView.DROP_SQL);
                statement.execute(WIDEN_TABLE_IDENTIFIERS_SQL);
            }
            if (exists(connection, "tables", "etl_column", null))
            {
                statement.execute(ADD_COLUMN_SOURCE_META_SQL);
                statement.execute(CREATE_COLUMN_MAPPING_SQL);
                int mappings = statement.executeUpdate(BACKFILL_COLUMN_MAPPING_SQL);
                if (mappings > 0)
                {
                    log.info("Backfilled {} column mapping(s) from etl_column", mappings);
                }
                statement.execute(CREATE_COLUMN_MAPPING_INDEXES_SQL);
                statement.execute(MIGRATE_COLUMN_MAPPING_SOURCE_INDEX_SQL);
            }
            statement.execute(CREATE_EXECUTION_TABLE_SQL);
            statement.execute(ADD_EXECUTION_IDENTITY_SQL);
            statement.execute(CREATE_EXECUTION_INDEXES_SQL);
            statement.execute(CREATE_FAILURE_TABLE_SQL);
            statement.execute(CREATE_FAILURE_INDEXES_SQL);
            statement.execute(CREATE_RECONCILE_TABLE_SQL);
            statement.execute(CREATE_RECONCILE_INDEXES_SQL);
            if (legacyHiveColumns)
            {
                int updated = statement.executeUpdate(BACKFILL_SQL);
                log.info("Backfilled target_options for {} etl_table row(s)", updated);
            }
        }
        if (hasTable && exists(connection, "tables", "etl_statistic", null)
            && exists(connection, "tables", "etl_jour", null)
            && exists(connection, "tables", "addax_log", null))
        {
            statement.execute(ADD_EXECUTION_CONTEXT_SQL);
            statement.execute(CREATE_EXECUTION_CONTEXT_INDEXES_SQL);
            statement.execute(ADD_EXECUTION_FOREIGN_KEYS_SQL);
        }
        if (hasSource && hasTable && exists(connection, "tables", "etl_target", null))
        {
            if (exists(connection, "columns", "etl_table", "target_id"))
            {
                int backfilled = statement.executeUpdate(BACKFILL_TARGET_ID_SQL);
                if (backfilled > 0)
                {
                    log.info("Backfilled target_id for {} etl_table row(s)", backfilled);
                }
                statement.execute(ADD_TABLE_SCOPE_INDEXES_SQL);
            }
            migrateTargetConnectKeys(connection);
            migrateHdfsTargetConfig(connection);
            refreshView(connection, statement);
        }
        if (legacyHiveColumns)
        {
            statement.execute(DROP_LEGACY_COLUMNS_SQL);
            log.info("Migrated etl_table Hive attributes (part_*/storage/compress) into target_options");
        }
    }

    /**
     * Some older seeds wrote the JDBC url as {@code jdbcUrl}; every runtime path reads {@code url}.
     * Copy it when {@code url} is missing, keeping the original key for compatibility.
     */
    private void migrateTargetConnectKeys(Connection connection) throws SQLException
    {
        List<TargetRow> rows = new ArrayList<>();
        try (PreparedStatement select = connection.prepareStatement(
            "select id, connect_config, writer_template_key from public.etl_target");
            ResultSet rs = select.executeQuery())
        {
            while (rs.next())
            {
                rows.add(new TargetRow(rs.getLong("id"), rs.getString("connect_config"),
                    rs.getString("writer_template_key")));
            }
        }
        int migrated = 0;
        for (TargetRow row : rows)
        {
            if (row.connectConfig() == null || row.connectConfig().isBlank())
            {
                continue;
            }
            ObjectNode config;
            try
            {
                JsonNode parsed = objectMapper.readTree(row.connectConfig());
                if (!(parsed instanceof ObjectNode objectNode))
                {
                    continue;
                }
                config = objectNode;
            }
            catch (Exception e)
            {
                log.warn("Skipping connect_config key migration for target {}: invalid JSON", row.id());
                continue;
            }
            JsonNode url = config.get("url");
            JsonNode legacyUrl = config.get("jdbcUrl");
            if (isBlank(url) && legacyUrl != null && legacyUrl.isTextual()
                && !legacyUrl.asText().isBlank())
            {
                config.set("url", legacyUrl);
                try (PreparedStatement update = connection.prepareStatement(
                    "update public.etl_target set connect_config = ? where id = ?"))
                {
                    update.setString(1, objectMapper.writeValueAsString(config));
                    update.setLong(2, row.id());
                    update.executeUpdate();
                }
                catch (Exception e)
                {
                    throw new SQLException("Failed to serialize connect_config for target " + row.id(), e);
                }
                migrated++;
            }
        }
        if (migrated > 0)
        {
            log.info("Copied jdbcUrl into url for {} target endpoint(s)", migrated);
        }
    }

    /**
     * Moves the pre-target-scoped Hive/HDFS settings into each HDFS target's {@code connect_config}.
     *
     * <p>Before multi-target support the HiveServer2 connection, HDFS prefix and storage defaults
     * lived in {@code sys_item} and were shared by every HDFS target. This fills only missing keys,
     * so an administrator who already edited a target keeps their values; the legacy rows are left
     * untouched for one release so rolling back the application still finds them.</p>
     */
    private void migrateHdfsTargetConfig(Connection connection) throws SQLException
    {
        if (!exists(connection, "tables", "sys_item", null))
        {
            return;
        }
        Map<String, Object> legacy = legacyHiveConfig(connection);
        if (legacy.isEmpty())
        {
            return;
        }
        List<TargetRow> rows = new ArrayList<>();
        try (PreparedStatement select = connection.prepareStatement("""
                select id, connect_config, writer_template_key
                  from public.etl_target
                 where upper(coalesce(writer_template_key, '')) = 'WH'
                    or upper(coalesce(target_type, '')) in ('HDFS', 'HIVE')
                """);
            ResultSet rs = select.executeQuery())
        {
            while (rs.next())
            {
                rows.add(new TargetRow(rs.getLong("id"), rs.getString("connect_config"),
                    rs.getString("writer_template_key")));
            }
        }
        int migrated = 0;
        for (TargetRow row : rows)
        {
            ObjectNode config;
            if (row.connectConfig() == null || row.connectConfig().isBlank())
            {
                config = JsonNodeFactory.instance.objectNode();
            }
            else
            {
                JsonNode parsed;
                try
                {
                    parsed = objectMapper.readTree(row.connectConfig());
                }
                catch (Exception e)
                {
                    log.warn("Skipping Hive config migration for target {}: invalid connect_config JSON", row.id());
                    continue;
                }
                if (!(parsed instanceof ObjectNode objectNode))
                {
                    log.warn("Skipping Hive config migration for target {}: connect_config is not an object", row.id());
                    continue;
                }
                config = objectNode;
            }
            boolean changed = false;
            for (Map.Entry<String, Object> entry : legacy.entrySet())
            {
                if (isBlank(config.get(entry.getKey())))
                {
                    config.set(entry.getKey(), objectMapper.valueToTree(entry.getValue()));
                    changed = true;
                }
            }
            String writerKey = row.writerKey();
            if (writerKey == null || writerKey.isBlank())
            {
                writerKey = "wH";
                changed = true;
            }
            if (!changed)
            {
                continue;
            }
            String json;
            try
            {
                json = objectMapper.writeValueAsString(config);
            }
            catch (Exception e)
            {
                throw new SQLException("Failed to serialize Hive target config for target " + row.id(), e);
            }
            try (PreparedStatement update = connection.prepareStatement(
                "update public.etl_target set connect_config = ?, writer_template_key = ? where id = ?"))
            {
                update.setString(1, json);
                update.setString(2, writerKey);
                update.setLong(3, row.id());
                update.executeUpdate();
            }
            migrated++;
        }
        if (migrated > 0)
        {
            log.info("Migrated legacy Hive/HDFS settings into {} target endpoint(s)", migrated);
        }
    }

    private Map<String, Object> legacyHiveConfig(Connection connection) throws SQLException
    {
        Map<String, String> items = new LinkedHashMap<>();
        try (PreparedStatement select = connection.prepareStatement("""
                select item_key, item_value
                  from public.sys_item
                 where dict_code = 1000
                   and item_key in ('HIVE_SERVER2', 'HDFS_PREFIX', 'HDFS_STORAGE_FORMAT',
                                    'HDFS_COMPRESS_FORMAT', 'HDFS_CONFIG')
                """);
            ResultSet rs = select.executeQuery())
        {
            while (rs.next())
            {
                items.put(rs.getString("item_key"), rs.getString("item_value"));
            }
        }
        String writerTemplate = null;
        try (PreparedStatement select = connection.prepareStatement(
            "select item_value from public.sys_item where dict_code = 5001 and item_key = 'wH'");
            ResultSet rs = select.executeQuery())
        {
            if (rs.next())
            {
                writerTemplate = rs.getString("item_value");
            }
        }

        Map<String, Object> values = new LinkedHashMap<>();
        JsonNode hive = parseJson(items.get("HIVE_SERVER2"));
        if (hive != null)
        {
            putText(values, "url", hive, "url");
            putText(values, "username", hive, "username");
            putText(values, "password", hive, "password");
            putText(values, "driverClassName", hive, "driverClassName");
            // Keep an explicit driver path only when the jar is not already in the shared driver
            // directory; after a move there, the isolated registry loads it without a pinned path.
            String legacyDriverPath = text(hive, "driverPath");
            if (legacyDriverPath != null && !legacyDriverPath.isBlank()
                && !driverRegistry.hasSharedDriver(legacyDriverPath))
            {
                values.put("driverPath", legacyDriverPath);
            }
        }
        JsonNode hdfsConfig = parseJson(items.get("HDFS_CONFIG"));
        if (hdfsConfig != null)
        {
            putText(values, "defaultFS", hdfsConfig, "defaultFS");
            putText(values, "hdfsPrefix", hdfsConfig, "hdfsPrefix");
            putText(values, "hdfsSitePath", hdfsConfig, "hdfsSitePath");
            putFlag(values, "enableKerberos", hdfsConfig, "enableKerberos");
            putObject(values, "hadoopConfig", hdfsConfig, "hadoopConfig");
        }
        JsonNode template = parseJson(writerTemplate);
        JsonNode parameter = template == null ? null : template.get("parameter");
        if (parameter instanceof ObjectNode)
        {
            putText(values, "defaultFS", parameter, "defaultFS");
            putText(values, "hdfsSitePath", parameter, "hdfsSitePath");
            putFlag(values, "enableKerberos", parameter, "haveKerberos");
            putObject(values, "hadoopConfig", parameter, "hadoopConfig");
        }
        putText(values, "hdfsPrefix", items.get("HDFS_PREFIX"));
        putText(values, "storageFormat", lower(items.get("HDFS_STORAGE_FORMAT")));
        putText(values, "compressFormat", lower(items.get("HDFS_COMPRESS_FORMAT")));
        Object prefix = values.get("hdfsPrefix");
        if (prefix instanceof String text)
        {
            values.put("hdfsPrefix", normalizePrefix(text));
        }
        values.values().removeIf(value -> value == null
            || (value instanceof String text && text.isBlank())
            || (value instanceof ObjectNode node && node.isEmpty()));
        return values;
    }

    private JsonNode parseJson(String value)
    {
        if (value == null || value.isBlank())
        {
            return null;
        }
        try
        {
            return objectMapper.readTree(value);
        }
        catch (Exception e)
        {
            log.warn("Ignoring unparseable legacy Hive/HDFS config: {}", e.getMessage());
            return null;
        }
    }

    private String text(JsonNode node, String key)
    {
        JsonNode value = node.get(key);
        return value == null || value.isNull() ? null : value.asText();
    }

    private void putText(Map<String, Object> values, String key, JsonNode node, String nodeKey)
    {
        JsonNode value = node.get(nodeKey);
        if (value != null && !value.isNull() && !value.asText().isBlank())
        {
            values.put(key, value.asText());
        }
    }

    private void putText(Map<String, Object> values, String key, String value)
    {
        if (value != null && !value.isBlank())
        {
            values.put(key, value);
        }
    }

    private void putFlag(Map<String, Object> values, String key, JsonNode node, String nodeKey)
    {
        JsonNode value = node.get(nodeKey);
        if (value != null && value.isBoolean())
        {
            values.put(key, value.asBoolean());
        }
    }

    private void putObject(Map<String, Object> values, String key, JsonNode node, String nodeKey)
    {
        JsonNode value = node.get(nodeKey);
        if (value instanceof ObjectNode object && !object.isEmpty())
        {
            values.put(key, object);
        }
    }

    private String lower(String value)
    {
        return value == null ? null : value.trim().toLowerCase(Locale.ROOT);
    }

    private String normalizePrefix(String prefix)
    {
        String value = prefix.trim();
        if (!value.startsWith("/"))
        {
            value = "/" + value;
        }
        while (value.length() > 1 && value.endsWith("/"))
        {
            value = value.substring(0, value.length() - 1);
        }
        return value;
    }

    private boolean isBlank(JsonNode value)
    {
        return value == null || value.isNull()
            || (value.isTextual() && value.asText().isBlank())
            || (value.isObject() && value.isEmpty());
    }

    private record TargetRow(long id, String connectConfig, String writerKey)
    {
    }

    /**
     * Recreates the view when the database holds a definition this build no longer expects.
     *
     * <p>The definition ({@link EtlTableView#CREATE_SQL}) carries its own fingerprint and {@link
     * EtlTableView} stores it as the view's comment, so "is the view current?" is answered by the view
     * itself instead of by a list of columns that someone has to remember to update. A change to the SQL
     * therefore reaches every database on the next start, and an unchanged one is left alone.</p>
     */
    private void refreshView(Connection connection, Statement statement) throws SQLException
    {
        if (EtlTableView.FINGERPRINT.equals(viewComment(connection)))
        {
            return;
        }
        statement.execute(EtlTableView.DROP_SQL);
        statement.execute(EtlTableView.CREATE_SQL);
        statement.execute(EtlTableView.commentSql());
        log.info("Recreated {} to expose the columns this build reads", EtlTableView.NAME);
    }

    /**
     * Comment of an existing {@code vw_etl_table_with_source}, {@code null} when it is missing or has no
     * comment. Looked up through {@code pg_class} rather than {@code obj_description('…'::regclass)}
     * because a missing relation must not raise here.
     */
    private String viewComment(Connection connection) throws SQLException
    {
        try (PreparedStatement ps = connection.prepareStatement(
            "select obj_description(c.oid, 'pg_class') from pg_class c "
                + "join pg_namespace n on n.oid = c.relnamespace "
                + "where n.nspname = 'public' and c.relname = ?"))
        {
            ps.setString(1, EtlTableView.NAME);
            try (ResultSet rs = ps.executeQuery())
            {
                return rs.next() ? rs.getString(1) : null;
            }
        }
    }

    /**
     * Whether a varchar column is still narrower than the definition this build expects. A missing
     * column or an unbounded type ({@code text}) needs no widening.
     */
    private boolean needsWidening(Connection connection, String table, String column, int minLength)
        throws SQLException
    {
        try (PreparedStatement ps = connection.prepareStatement("""
                select coalesce(character_maximum_length, 0)
                  from information_schema.columns
                 where table_schema = 'public' and table_name = ? and column_name = ?
                """))
        {
            ps.setString(1, table);
            ps.setString(2, column);
            try (ResultSet rs = ps.executeQuery())
            {
                if (!rs.next())
                {
                    return false;
                }
                long length = rs.getLong(1);
                return length > 0 && length < minLength;
            }
        }
    }

    /**
     * Existence check on the migration's own connection: the DDL above is uncommitted, so a separate pooled
     * connection (JdbcTemplate) would not see it. {@code relation} and {@code name} are constants from this
     * class, not input.
     */
    private boolean exists(Connection connection, String relation, String name, String column)
        throws SQLException
    {
        String sql = "select count(*) from information_schema." + relation
            + " where table_schema = 'public' and table_name = ?"
            + (column == null ? "" : " and column_name = ?");
        try (PreparedStatement ps = connection.prepareStatement(sql))
        {
            ps.setString(1, name);
            if (column != null)
            {
                ps.setString(2, column);
            }
            try (ResultSet rs = ps.executeQuery())
            {
                return rs.next() && rs.getInt(1) > 0;
            }
        }
    }
