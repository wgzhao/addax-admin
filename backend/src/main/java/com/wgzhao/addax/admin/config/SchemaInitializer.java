package com.wgzhao.addax.admin.config;

import jakarta.annotation.PostConstruct;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.jdbc.core.ConnectionCallback;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

/**
 * Startup schema migration for databases created by an older release.
 *
 * <p>There is no migration framework in this project and {@code scripts/schema.sql} is written by hand for
 * fresh installs, so upgrading an existing database happens here. Everything lives in one ordered pipeline
 * on purpose: the steps below all touch {@code vw_etl_table_with_source} (each release exposes another
 * column through it), and a step that recreates the view before the column it selects exists aborts
 * startup. That is exactly how the 4.2.1 upgrade of a 4.2.0 database failed — the target-options migration
 * recreated the view with {@code s.calendar} in it while the calendar migration, which adds that column,
 * was still waiting for its turn in a separate bean.</p>
 *
 * <p>The pipeline keeps the properties of the initializers it replaces:</p>
 * <ul>
 *   <li>it runs in a single transaction behind a PostgreSQL advisory transaction lock, so concurrent
 *       instances cannot interleave, and PostgreSQL's transactional DDL rolls the whole upgrade back on
 *       failure. A failure aborts startup on purpose — serving traffic against a half-migrated schema (a
 *       view without its columns) would be worse than not starting.</li>
 *   <li>every step is guarded and repeatable, so an interrupted run can simply be retried;</li>
 *   <li>it runs from {@code @PostConstruct}, i.e. before the web server accepts requests, before the
 *       scheduled refresh starts, and before any query can reach the columns it adds;</li>
 *   <li>the view is refreshed last, from {@link EtlTableView#CREATE_SQL}, so its definition may reference
 *       every column the earlier steps add.</li>
 * </ul>
 */
@Component
@RequiredArgsConstructor
@Slf4j
public class SchemaInitializer
{
    /**
     * Arbitrary but stable key; any instance running this migration contends for the same lock.
     */
    private static final long MIGRATION_LOCK_KEY = 662012001L;

    private static final String CREATE_AUDIT_EVENT_SQL = """
        create table if not exists public.audit_event (
            id bigint generated by default as identity primary key,
            event_id uuid not null unique,
            occurred_at timestamp with time zone not null default clock_timestamp(),
            request_id varchar(64),
            actor_type varchar(16) not null default 'USER',
            actor_username varchar(100),
            actor_roles jsonb not null default '[]'::jsonb,
            session_id varchar(64),
            action varchar(80) not null,
            category varchar(32) not null,
            severity varchar(16) not null,
            resource_type varchar(64),
            resource_id varchar(128),
            resource_name varchar(255),
            outcome varchar(16) not null,
            http_method varchar(8),
            request_path varchar(512),
            client_ip inet,
            user_agent varchar(512),
            node_id varchar(128),
            before_data jsonb,
            after_data jsonb,
            changed_fields jsonb not null default '[]'::jsonb,
            error_code varchar(64),
            error_message varchar(1000),
            metadata jsonb not null default '{}'::jsonb
        )
        """;

    private static final String CREATE_AUDIT_INDEXES_SQL = """
        create index if not exists idx_audit_event_occurred_at
            on public.audit_event (occurred_at desc, id desc);
        create index if not exists idx_audit_event_actor_occurred
            on public.audit_event (actor_username, occurred_at desc);
        create index if not exists idx_audit_event_action_occurred
            on public.audit_event (action, occurred_at desc);
        create index if not exists idx_audit_event_resource_occurred
            on public.audit_event (resource_type, resource_id, occurred_at desc);
        create index if not exists idx_audit_event_request
            on public.audit_event (request_id);
        create index if not exists idx_audit_event_outcome_occurred
            on public.audit_event (outcome, occurred_at desc)
        """;

    private static final String CREATE_AUDIT_APPEND_ONLY_SQL = """
        create or replace function public.fn_audit_event_append_only()
        returns trigger
        language plpgsql
        as $$
        begin
            if tg_op = 'DELETE' and current_setting('addax.audit_purge', true) = 'on' then
                return old;
            end if;
            raise exception 'audit_event is append-only';
        end;
        $$
        """;

    private static final String CREATE_AUDIT_APPEND_ONLY_TRIGGER_SQL = """
        drop trigger if exists trg_audit_event_append_only on public.audit_event;
        create trigger trg_audit_event_append_only
            before update or delete on public.audit_event
            for each row execute function public.fn_audit_event_append_only()
        """;

    /**
     * The out-of-the-box calendar every source uses when it has no explicit one.
     */
    private static final int WORK_DAY_DICT_CODE = 1022;

    private static final String ADD_CALENDAR_COLUMN_SQL =
        "alter table public.etl_source add column if not exists calendar varchar(32)";

    private static final String SEED_WORK_DAY_DICT_SQL = """
        insert into public.sys_dict (code, name, classification, remark)
        values (1022, '工作日历', 'FR', '工作日(含调休)日期表，item_key 为 yyyyMMdd 的业务日期')
        on conflict (code) do nothing
        """;

    private static final String ADD_TARGET_OPTIONS_SQL =
        "alter table public.etl_table add column if not exists target_options jsonb";

    private static final String ADD_SCHEMA_OWNERSHIP_SQL = """
        alter table public.etl_table
            add column if not exists schema_management_mode varchar(16) not null default 'MANAGED',
            add column if not exists target_schema_fingerprint varchar(64)
        """;

    private static final String CREATE_COLUMN_MAPPING_SQL = """
        create table if not exists public.etl_column_mapping (
            id bigint generated by default as identity primary key,
            tid bigint not null references public.etl_table(id) on delete restrict,
            source_column_name varchar(255) not null,
            target_column_name varchar(255) not null,
            ordinal_no integer not null,
            created_at timestamp without time zone not null default current_timestamp,
            updated_at timestamp without time zone not null default current_timestamp
        )
        """;

    /**
     * A source column that was dropped and later re-added leaves both foo and __deleted__foo behind.
     * Legacy rows can also differ only by whitespace or case. The mapping contract is case-insensitive
     * and one-to-one, so collapse those rows before the unique indexes are created: prefer the live
     * column, then the lowest column_id, both deterministic.
     */
    private static final String BACKFILL_COLUMN_MAPPING_SQL = """
        insert into public.etl_column_mapping (
            tid, source_column_name, target_column_name, ordinal_no
        )
        select distinct on (c.tid, lower(btrim(regexp_replace(c.column_name, '^__deleted__', ''))))
               c.tid,
               btrim(regexp_replace(c.column_name, '^__deleted__', '')),
               btrim(regexp_replace(c.column_name, '^__deleted__', '')),
               coalesce(c.column_id, 0)
          from public.etl_column c
         where btrim(regexp_replace(c.column_name, '^__deleted__', '')) <> ''
           and not exists (
               select 1 from public.etl_column_mapping m where m.tid = c.tid
           )
         order by c.tid,
                  lower(btrim(regexp_replace(c.column_name, '^__deleted__', ''))),
                  (left(c.column_name, 11) = '__deleted__'),
                  c.column_id nulls last,
                  c.column_name
        """;

    private static final String CREATE_COLUMN_MAPPING_INDEXES_SQL = """
        create unique index if not exists uk_column_mapping_tid_source
            on public.etl_column_mapping (tid, lower(source_column_name));
        create unique index if not exists uk_column_mapping_tid_target
            on public.etl_column_mapping (tid, lower(target_column_name))
        """;

    private static final String ADD_TABLE_RETIREMENT_SQL = """
        alter table public.etl_table
            add column if not exists retired_at timestamp without time zone,
            add column if not exists retired_by varchar(100)
        """;

    private static final String CREATE_EXECUTION_TABLE_SQL = """
        create table if not exists public.etl_execution (
            id bigint generated by default as identity primary key,
            tid bigint not null,
            job_queue_id bigint,
            attempt_no integer not null default 1,
            biz_date date not null,
            source_db varchar(64),
            source_table varchar(255),
            source_code varchar(50),
            source_name varchar(200),
            target_db varchar(64),
            target_table varchar(255),
            target_code varchar(50),
            target_name varchar(200),
            status varchar(16) not null default 'running',
            started_at timestamp without time zone not null default current_timestamp,
            finished_at timestamp without time zone,
            snapshot_version integer not null default 1,
            config_snapshot jsonb not null,
            job_digest varchar(64),
            error_message text
        )
        """;

    private static final String ADD_EXECUTION_IDENTITY_SQL = """
        alter table public.etl_execution
            add column if not exists source_db varchar(64),
            add column if not exists source_table varchar(255),
            add column if not exists source_code varchar(50),
            add column if not exists source_name varchar(200),
            add column if not exists target_db varchar(64),
            add column if not exists target_table varchar(255),
            add column if not exists target_code varchar(50),
            add column if not exists target_name varchar(200)
        """;

    private static final String CREATE_EXECUTION_INDEXES_SQL = """
        create index if not exists idx_etl_execution_tid_started
            on public.etl_execution (tid, started_at desc, id desc);
        create index if not exists idx_etl_execution_queue
            on public.etl_execution (job_queue_id)
        """;

    private static final String ADD_EXECUTION_CONTEXT_SQL = """
        alter table public.etl_statistic add column if not exists execution_id bigint;
        alter table public.etl_jour add column if not exists execution_id bigint;
        alter table public.etl_jour add column if not exists context_snapshot jsonb;
        alter table public.addax_log add column if not exists execution_id bigint
        """;

    private static final String CREATE_EXECUTION_CONTEXT_INDEXES_SQL = """
        create index if not exists idx_etl_statistic_execution on public.etl_statistic (execution_id);
        create index if not exists idx_etl_jour_execution on public.etl_jour (execution_id);
        create index if not exists idx_addax_log_execution on public.addax_log (execution_id)
        """;

    private static final String ADD_EXECUTION_FOREIGN_KEYS_SQL = """
        do $$
        begin
            if not exists (select 1 from pg_constraint where conname = 'etl_execution_tid_fk') then
                alter table public.etl_execution
                    add constraint etl_execution_tid_fk
                    foreign key (tid) references public.etl_table(id) on delete restrict;
            end if;
            if not exists (select 1 from pg_constraint where conname = 'etl_statistic_execution_fk') then
                alter table public.etl_statistic
                    add constraint etl_statistic_execution_fk
                    foreign key (execution_id) references public.etl_execution(id) on delete restrict;
            end if;
            if not exists (select 1 from pg_constraint where conname = 'etl_jour_execution_fk') then
                alter table public.etl_jour
                    add constraint etl_jour_execution_fk
                    foreign key (execution_id) references public.etl_execution(id) on delete restrict;
            end if;
            if not exists (select 1 from pg_constraint where conname = 'addax_log_execution_fk') then
                alter table public.addax_log
                    add constraint addax_log_execution_fk
                    foreign key (execution_id) references public.etl_execution(id) on delete restrict;
            end if;
        end
        $$
        """;

    private static final String BACKFILL_SQL = """
        update public.etl_table
           set target_options = jsonb_build_object('hdfs', jsonb_build_object(
                 'partKind', coalesce(part_kind, 'D'),
                 'partName', coalesce(part_name, ''),
                 'partFormat', coalesce(nullif(part_format, ''), 'yyyyMMdd'),
                 'storageFormat', coalesce(nullif(storage_format, ''), 'orc'),
                 'compressFormat', coalesce(nullif(compress_format, ''), 'snappy')))
         where target_options is null
        """;

    private static final String DROP_LEGACY_COLUMNS_SQL = """
        alter table public.etl_table
            drop column if exists part_kind,
            drop column if exists part_name,
            drop column if exists part_format,
            drop column if exists storage_format,
            drop column if exists compress_format
        """;

    /**
     * Marker of the pre-4.2.1 Hive attributes: present means the target-options move has not run yet.
     */
    private static final String LEGACY_COLUMN = "part_name";

    private final JdbcTemplate jdbcTemplate;

    @PostConstruct
    public void migrate()
    {
        jdbcTemplate.execute((ConnectionCallback<Void>) connection -> {
            boolean autoCommit = connection.getAutoCommit();
            connection.setAutoCommit(false);
            try (Statement statement = connection.createStatement())
            {
                statement.execute("select pg_advisory_xact_lock(" + MIGRATION_LOCK_KEY + ")");
                upgrade(connection, statement);
                connection.commit();
                return null;
            }
            catch (SQLException | RuntimeException e)
            {
                connection.rollback();
                throw e;
            }
            finally
            {
                connection.setAutoCommit(autoCommit);
            }
        });
    }

    private void upgrade(Connection connection, Statement statement) throws SQLException
    {
        statement.execute(CREATE_AUDIT_EVENT_SQL);
        statement.execute(CREATE_AUDIT_INDEXES_SQL);
        statement.execute(CREATE_AUDIT_APPEND_ONLY_SQL);
        statement.execute(CREATE_AUDIT_APPEND_ONLY_TRIGGER_SQL);
        boolean hasSource = exists(connection, "tables", "etl_source", null);
        boolean hasTable = exists(connection, "tables", "etl_table", null);
        if (!hasSource && !hasTable)
        {
            log.info("etl_source/etl_table not found, skip schema migration");
            return;
        }
        if (hasSource)
        {
            statement.execute(ADD_CALENDAR_COLUMN_SQL);
            if (statement.executeUpdate(SEED_WORK_DAY_DICT_SQL) > 0)
            {
                log.info("Seeded the work-day calendar dictionary (code {})", WORK_DAY_DICT_CODE);
            }
        }
        boolean legacyHiveColumns = hasTable && exists(connection, "columns", "etl_table", LEGACY_COLUMN);
        if (hasTable)
        {
            statement.execute(ADD_TARGET_OPTIONS_SQL);
            statement.execute(ADD_SCHEMA_OWNERSHIP_SQL);
            statement.execute(ADD_TABLE_RETIREMENT_SQL);
            if (exists(connection, "tables", "etl_column", null))
            {
                statement.execute(CREATE_COLUMN_MAPPING_SQL);
                int mappings = statement.executeUpdate(BACKFILL_COLUMN_MAPPING_SQL);
                if (mappings > 0)
                {
                    log.info("Backfilled {} column mapping(s) from etl_column", mappings);
                }
                statement.execute(CREATE_COLUMN_MAPPING_INDEXES_SQL);
            }
            statement.execute(CREATE_EXECUTION_TABLE_SQL);
            statement.execute(ADD_EXECUTION_IDENTITY_SQL);
            statement.execute(CREATE_EXECUTION_INDEXES_SQL);
            if (legacyHiveColumns)
            {
                int updated = statement.executeUpdate(BACKFILL_SQL);
                log.info("Backfilled target_options for {} etl_table row(s)", updated);
            }
        }
        if (hasTable && exists(connection, "tables", "etl_statistic", null)
            && exists(connection, "tables", "etl_jour", null)
            && exists(connection, "tables", "addax_log", null))
        {
            statement.execute(ADD_EXECUTION_CONTEXT_SQL);
            statement.execute(CREATE_EXECUTION_CONTEXT_INDEXES_SQL);
            statement.execute(ADD_EXECUTION_FOREIGN_KEYS_SQL);
        }
        if (hasSource && hasTable && exists(connection, "tables", "etl_target", null))
        {
            refreshView(connection, statement);
        }
        if (legacyHiveColumns)
        {
            statement.execute(DROP_LEGACY_COLUMNS_SQL);
            log.info("Migrated etl_table Hive attributes (part_*/storage/compress) into target_options");
        }
    }

    /**
     * Recreates the view when the database holds a definition this build no longer expects.
     *
     * <p>The definition ({@link EtlTableView#CREATE_SQL}) carries its own fingerprint and {@link
     * EtlTableView} stores it as the view's comment, so "is the view current?" is answered by the view
     * itself instead of by a list of columns that someone has to remember to update. A change to the SQL
     * therefore reaches every database on the next start, and an unchanged one is left alone.</p>
     */
    private void refreshView(Connection connection, Statement statement) throws SQLException
    {
        if (EtlTableView.FINGERPRINT.equals(viewComment(connection)))
        {
            return;
        }
        statement.execute(EtlTableView.DROP_SQL);
        statement.execute(EtlTableView.CREATE_SQL);
        statement.execute(EtlTableView.commentSql());
        log.info("Recreated {} to expose the columns this build reads", EtlTableView.NAME);
    }

    /**
     * Comment of an existing {@code vw_etl_table_with_source}, {@code null} when it is missing or has no
     * comment. Looked up through {@code pg_class} rather than {@code obj_description('…'::regclass)}
     * because a missing relation must not raise here.
     */
    private String viewComment(Connection connection) throws SQLException
    {
        try (PreparedStatement ps = connection.prepareStatement(
            "select obj_description(c.oid, 'pg_class') from pg_class c "
                + "join pg_namespace n on n.oid = c.relnamespace "
                + "where n.nspname = 'public' and c.relname = ?"))
        {
            ps.setString(1, EtlTableView.NAME);
            try (ResultSet rs = ps.executeQuery())
            {
                return rs.next() ? rs.getString(1) : null;
            }
        }
    }

    /**
     * Existence check on the migration's own connection: the DDL above is uncommitted, so a separate pooled
     * connection (JdbcTemplate) would not see it. {@code relation} and {@code name} are constants from this
     * class, not input.
     */
    private boolean exists(Connection connection, String relation, String name, String column)
        throws SQLException
    {
        String sql = "select count(*) from information_schema." + relation
            + " where table_schema = 'public' and table_name = ?"
            + (column == null ? "" : " and column_name = ?");
        try (PreparedStatement ps = connection.prepareStatement(sql))
        {
            ps.setString(1, name);
            if (column != null)
            {
                ps.setString(2, column);
            }
            try (ResultSet rs = ps.executeQuery())
            {
                return rs.next() && rs.getInt(1) > 0;
            }
        }
    }
}
