package com.wgzhao.addax.admin.config.schema;

import com.wgzhao.addax.admin.config.EtlTableView;
import lombok.extern.slf4j.Slf4j;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

/** Creates the alert event and delivery tables before any collection schema exists. */
@Slf4j
public final class AlertSchema
{
        public static final String CREATE_ALERT_TABLES_SQL = """
        create table if not exists public.alert_channel (
            id bigint generated by default as identity primary key,
            name varchar(100) not null,
            type varchar(32) not null,
            config_ciphertext text not null,
            enabled boolean not null default false,
            rate_limit_per_minute integer not null default 60,
            last_test_at timestamp with time zone,
            last_test_ok boolean,
            created_by varchar(50),
            created_at timestamp with time zone not null default current_timestamp,
            updated_at timestamp with time zone not null default current_timestamp
        );
        create table if not exists public.alert_rule (
            id bigint generated by default as identity primary key,
            name varchar(100) not null,
            event_type varchar(64) not null,
            severity varchar(16) not null,
            scope_type varchar(16) not null,
            scope_value varchar(255),
            channel_ids jsonb not null default '[]'::jsonb,
            cooldown_secs integer not null default 300,
            group_window_secs integer not null default 60,
            ack_required boolean not null default false,
            escalate_after_secs integer,
            escalation_channel_ids jsonb,
            enabled boolean not null default true,
            created_at timestamp with time zone not null default current_timestamp,
            updated_at timestamp with time zone not null default current_timestamp
        );
        create table if not exists public.alert_event (
            id bigint generated by default as identity primary key,
            event_key varchar(255) not null,
            event_type varchar(64) not null,
            severity varchar(16) not null,
            scope_type varchar(16) not null,
            scope_value varchar(255),
            status varchar(16) not null,
            first_seen timestamp with time zone not null,
            last_seen timestamp with time zone not null,
            fire_count integer not null default 1,
            payload jsonb,
            resolved_at timestamp with time zone
        );
        create table if not exists public.alert_delivery (
            id bigint generated by default as identity primary key,
            event_id bigint not null references public.alert_event(id) on delete cascade,
            channel_id bigint references public.alert_channel(id) on delete set null,
            channel_name varchar(100),
            status varchar(24) not null,
            attempts integer not null default 0,
            next_retry_at timestamp with time zone,
            response_code integer,
            response_body text,
            last_error varchar(1000),
            sent_at timestamp with time zone,
            locked_by varchar(100),
            locked_until timestamp with time zone,
            created_at timestamp with time zone not null default current_timestamp,
            updated_at timestamp with time zone not null default current_timestamp
        );
        create table if not exists public.alert_silence (
            id bigint generated by default as identity primary key,
            scope_type varchar(16) not null,
            scope_value varchar(255),
            starts_at timestamp with time zone not null,
            ends_at timestamp with time zone not null,
            reason varchar(255),
            created_by varchar(50),
            created_at timestamp with time zone not null default current_timestamp
        )
        """;

        public static final String CREATE_ALERT_INDEXES_SQL = """
        create unique index if not exists uk_alert_channel_name
            on public.alert_channel (lower(name));
        create unique index if not exists uk_alert_event_open
            on public.alert_event (event_key) where status in ('FIRING', 'SILENCED');
        create index if not exists idx_alert_event_last_seen
            on public.alert_event (last_seen desc, id desc);
        create index if not exists idx_alert_event_type_status
            on public.alert_event (event_type, status, last_seen desc);
        create unique index if not exists uk_alert_delivery_event_channel
            on public.alert_delivery (event_id, channel_id) where channel_id is not null;
        create index if not exists idx_alert_delivery_pending
            on public.alert_delivery (status, next_retry_at);
        create index if not exists idx_alert_delivery_event
            on public.alert_delivery (event_id);
        create index if not exists idx_alert_delivery_channel
            on public.alert_delivery (channel_id, created_at desc);
        create index if not exists idx_alert_silence_window
            on public.alert_silence (ends_at, starts_at)
        """;

    public static void ensure(Statement statement) throws SQLException
    {
        statement.execute(CREATE_ALERT_TABLES_SQL);
        statement.execute(CREATE_ALERT_INDEXES_SQL);
    }

    private AlertSchema()
    {
    }
}
